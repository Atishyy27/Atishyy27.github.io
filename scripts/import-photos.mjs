// scripts/import-photos.mjs
// Turns a folder of photos into web assets, without any of them leaving the Mac.
//
// Why this exists rather than a LinkedIn pull: LinkedIn has no API that serves
// a member their own post images (it is partner-gated), and scraping the site
// is off the table. The two ways in are therefore local: drop the files in, or
// request the official data export from LinkedIn (Settings, Data privacy, Get a
// copy of your data, tick Posts) and drop that folder's images in.
//
// What it does to every file:
//   - resizes the long edge to 1400px, which is as large as the page ever shows
//   - re-encodes as webp at quality 82
//   - STRIPS ALL METADATA. A phone photo carries GPS coordinates, the device
//     and the timestamp. sharp drops them unless asked to keep them, and this
//     never asks, so publishing a photo does not publish where it was taken.
//
// Layout:
//   photos-inbox/<key>/anything.jpg      ->   public/photos/<key>-01.webp
// where <key> matches an achievement's `photos` field in content/achievements.ts.
//
// Run:  node scripts/import-photos.mjs
// Then: check public/photos/, commit if it looks right.

import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const INBOX = path.join(process.cwd(), "photos-inbox");
const OUT_DIR = path.join(process.cwd(), "public", "photos");
const MANIFEST = path.join(process.cwd(), "src", "content", "photos.ts");
const LONG_EDGE = 1400;
const OK = /\.(jpe?g|png|webp|tiff?)$/i;

if (!fs.existsSync(INBOX)) {
  console.log(`FAIL  ${path.relative(process.cwd(), INBOX)} does not exist.`);
  console.log("      mkdir -p photos-inbox/<achievement-key> and put the images in it.");
  console.log("      keys come from the `photos` field in src/content/achievements.ts");
  process.exit(1);
}

const keys = fs
  .readdirSync(INBOX, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  // Underscore-prefixed folders are scratch, not achievement keys.
  // stage-photos.sh unpacks a download into photos-inbox/_staging/ for sorting,
  // and without this line that staging folder is read as an achievement: it
  // imported 63 unsorted files under the key "_staging" on 24 Oct 2026, which
  // would have published every image in the drop, in arrival order, attached
  // to nothing.
  .filter((e) => !e.name.startsWith("_"))
  .map((e) => e.name)
  .sort();

if (keys.length === 0) {
  console.log("FAIL  photos-inbox/ has no subfolders, so there is nothing keyed to an achievement.");
  process.exit(1);
}

fs.mkdirSync(OUT_DIR, { recursive: true });

const manifest = {};
let written = 0;
let skipped = 0;

for (const key of keys) {
  const dir = path.join(INBOX, key);
  const files = fs.readdirSync(dir).filter((f) => OK.test(f)).sort();
  if (files.length === 0) {
    console.log(`SKIP  ${key}: no images`);
    continue;
  }

  const shots = [];
  let n = 0;
  for (const file of files) {
    n++;
    const src = path.join(dir, file);
    const name = `${key}-${String(n).padStart(2, "0")}.webp`;
    const dest = path.join(OUT_DIR, name);

    try {
      const buf = await sharp(src)
        .rotate()                                   // honour the EXIF orientation before dropping EXIF
        .resize({ width: LONG_EDGE, height: LONG_EDGE, fit: "inside", withoutEnlargement: true })
        .webp({ quality: 82 })
        .toBuffer();
      const meta = await sharp(buf).metadata();
      fs.writeFileSync(dest, buf);
      shots.push({ src: `/photos/${name}`, w: meta.width, h: meta.height });
      written++;
      console.log(`PASS  ${key}/${file} -> public/photos/${name}  ${meta.width}x${meta.height}, ${Math.round(buf.length / 1024)} KB`);
    } catch (err) {
      skipped++;
      console.log(`FAIL  ${key}/${file}: ${err.message}`);
    }
  }
  if (shots.length) manifest[key] = shots;
}

const body = Object.entries(manifest)
  .map(
    ([key, shots]) =>
      `  "${key}": [\n` +
      shots.map((s) => `    { src: "${s.src}", w: ${s.w}, h: ${s.h} },`).join("\n") +
      `\n  ],`
  )
  .join("\n");

fs.writeFileSync(
  MANIFEST,
  `// GENERATED by scripts/import-photos.mjs. Do not edit.
// Photos imported from the local photos-inbox/ folder on ${new Date().toISOString().slice(0, 10)}.
// Resized to a ${LONG_EDGE}px long edge, re-encoded as webp, and stripped of all
// metadata, so no GPS coordinate or device name ships with the site.
export type Photo = { src: string; w: number; h: number };

export const PHOTOS: Record<string, Photo[]> = {
${body}
};
`
);

console.log(`\n${written} written, ${skipped} failed, ${Object.keys(manifest).length} keys`);
console.log(written > 0 ? "ALL PASS" : "FAIL  nothing was written");
process.exit(written > 0 ? 0 : 1);
